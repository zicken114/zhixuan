export function useI18n() {
  const settingsStore = useSettingsStore();
  const language = computed(() => settingsStore.config.appLanguage);

  const t = (key: string, vars?: Record<string, string | number>): string => {
    const template = messages[language.value]?.[key] || messages.en[key] || key;
    if (!vars) return template;
    return Object.entries(vars).reduce((text, [name, value]) => {
      const token = `{${name}}`;
      return text.split(token).join(String(value));
    }, template);
  };

  return { t, language };
}
